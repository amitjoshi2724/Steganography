typedef struct
{
   double x ;
   double y ;
   double z ;
   //
} triple ;
//
triple e = { 0.50 , 0.50 , -1.00 } ; // the eye
//triple g = { 0.00 , 1.25 , -0.50 } ; // the light
//
double dotp( triple t , triple u )
{
   return t.x * u.x + t.y * u.y + t.z * u.z ;
}
//
void diff( triple* t , triple u , triple v ) // t = u - v
{
   t->x = u.x - v.x ;
   t->y = u.y - v.y ;
   t->z = u.z - v.z ;
}
